"""Generate a small C++ program from one salmon release's own alevin source, for the oracle.

    python harness.py SRC_DIR OUT.cpp

SRC_DIR is a checkout of salmon at a tag. The program takes `sort_indexes`, `gaussianKDE`,
`getLeftBoundary`, `dumpFeatures` (where it exists) and `sampleTrueBarcodes` verbatim from
`src/Alevin.cpp`, the `--keepCBFraction` statement of `processBarcodes`, and the declarations of
the fields of `AlevinOpts` they use (`include/AlevinOpts.hpp`). Only stand-ins are new: a logger
that prints nothing (for spdlog), `std::filesystem::path` (for boost's), `nonstd` string views.

    harness MODE [VALUE] < counts.txt      MODE: knee | expect E | force F | keep P

reads one count per line (barcode i is line i; counts above 0 only, as alevin's table holds) and
prints `knee`, `gauss` (the density's prediction and whether it was taken) for the knee,
`cells` (alevin's high-confidence count), `low` (its reported band), then `cell <i>` for the
high-confidence barcodes in alevin's order and `white <i>` for the whitelist.
"""

import re
import sys

FIELDS = ("forceCells", "expectCells", "freqThreshold", "maxNumBarcodes", "lowRegionMinNumBarcodes",
          "keepCBFraction", "dumpfeatures", "kneeCutoff", "totalLowConfidenceCBs", "numCells", "readsThrown")


def function(text, name):
    m = re.search(r"\n[^\n;{}]*\b" + name + r"\s*\([^;{]*\)\s*\{", text)
    if not m:
        return None
    start = text.rfind("\n", 0, m.start() - 1)
    head = text[start:m.start()]
    if head.strip().startswith("template"):  # keep the template line above it
        m_start = start
    else:
        m_start = m.start()
    i = text.index("{", m.end() - 1)
    depth = 0
    for j in range(i, len(text)):
        depth += text[j] == "{"
        depth -= text[j] == "}"
        if depth == 0:
            return text[m_start:j + 1]
    raise ValueError("unbalanced braces in " + name)


def main(src, out):
    with open(src + "/src/Alevin.cpp") as handle:
        alevin = handle.read()
    with open(src + "/include/AlevinOpts.hpp") as handle:
        opts = handle.read()
    fields = []
    for name in FIELDS:
        m = re.search(r"\n\s*((?:std::)?[A-Za-z_0-9:]+)\s+" + name + r"\s*;", opts)
        if m:
            fields.append((m.group(1), name))
    present = {name for _, name in fields}
    freq_type = re.search(r"sampleTrueBarcodes\s*\(\s*const std::vector<(\w+)>&", alevin).group(1)
    parts = [function(alevin, name) for name in ("sort_indexes", "gaussianKDE", "getLeftBoundary", "dumpFeatures", "sampleTrueBarcodes")]
    keep = re.search(r"if \(aopt\.keepCBFraction (?:!=|>=|>) 0\.0\) \{(.*?)\n\s*\}", alevin, re.S)
    keep_code = keep.group(1) if keep else 'std::cerr << "no --keepCBFraction" << std::endl; return 2;'
    declarations = "\n".join(f"  {t} {n}{{}};" for t, n in fields)
    defaults = "\n".join(f"  aopt.{n} = {v};" for n, v in (("freqThreshold", 10), ("maxNumBarcodes", 100000),
                                                            ("lowRegionMinNumBarcodes", 200), ("dumpfeatures", "false"))
                         if n in present)
    setters = {
        "expect": "aopt.expectCells = value;" if "expectCells" in present else 'std::cerr << "no --expectCells" << std::endl; return 2;',
        "force": "aopt.forceCells = value;" if "forceCells" in present else 'std::cerr << "no --forceCells" << std::endl; return 2;',
        "keep": ("aopt.keepCBFraction = fraction;\n    std::vector<" + freq_type + ">& freqCounter = freq;" + keep_code)
                if "keepCBFraction" in present else 'std::cerr << "no --keepCBFraction" << std::endl; return 2;',
    }
    high = "aopt.kneeCutoff" if "kneeCutoff" in present else "(gaussOk ? gauss : knee)"
    low = "aopt.totalLowConfidenceCBs" if "totalLowConfidenceCBs" in present else "lowRegionNumBarcodes"
    program = f"""// Generated by oracles/alevin/harness.py from salmon's own src/Alevin.cpp (GPL-3).
#include <algorithm>
#include <cmath>
#include <cstdint>
#include <cstdlib>
#include <filesystem>
#include <fstream>
#include <iostream>
#include <memory>
#include <numeric>
#include <string>
#include <string_view>
#include <unordered_map>
#include <unordered_set>
#include <vector>

namespace nonstd {{
template <class C> using basic_string_view = std::basic_string_view<C>;
inline std::string to_string(std::string_view s) {{ return std::string(s); }}
}}
using TrueBcsT = std::unordered_set<std::string>;
static const char* green = "";
static const char* red = "";
static const char* RESET_COLOR = "";
struct Log {{
  template <class... A> void info(A&&...) {{}}
  template <class... A> void warn(A&&...) {{}}
  template <class... A> void error(A&&...) {{}}
  void flush() {{}}
}};
struct Opts {{
{declarations}
  std::shared_ptr<Log> jointLog = std::make_shared<Log>();
  std::filesystem::path outputDirectory{{"."}};
}};
template <typename ProtocolT> struct AlevinOpts : Opts {{}};

{chr(10).join(p for p in parts if p)}

int main(int argc, char** argv) {{
  std::string mode = argv[1];
  uint64_t value = argc > 2 ? std::strtoull(argv[2], nullptr, 10) : 0;
  double fraction = argc > 2 ? std::strtod(argv[2], nullptr) : 0.0;
  std::vector<{freq_type}> freq;
  for (std::string line; std::getline(std::cin, line);) freq.push_back(static_cast<{freq_type}>(std::stoull(line)));
  std::vector<std::string> names(freq.size());
  std::unordered_map<uint32_t, nonstd::basic_string_view<char>> colMap;
  for (size_t i = 0; i < freq.size(); i++) {{ names[i] = std::to_string(i); }}
  for (size_t i = 0; i < freq.size(); i++) {{ colMap[i] = names[i]; }}
  AlevinOpts<int> aopt;
{defaults}
  if (mode == "expect") {{ {setters["expect"]} }}
  else if (mode == "force") {{ {setters["force"]} }}
  else if (mode == "keep") {{ {setters["keep"]} }}
  {freq_type} knee = 0, gauss = 0;
  bool gaussOk = false;
  std::vector<size_t> sortedIdx = sort_indexes(freq);
  if (mode == "knee") {{
    {freq_type} top = std::min(static_cast<size_t>(aopt.maxNumBarcodes), freq.size());
    knee = getLeftBoundary(sortedIdx, top, freq);
    double invCovariance{{0.0}}, normFactor{{0.0}};
    gaussOk = gaussianKDE(freq, sortedIdx, invCovariance, normFactor, knee, gauss);
    std::cout << "knee " << knee << "\\n" << "gauss " << gauss << " " << gaussOk << "\\n";
  }}
  TrueBcsT trueBarcodes;
  size_t lowRegionNumBarcodes{{0}};
  sampleTrueBarcodes(freq, trueBarcodes, lowRegionNumBarcodes, colMap, aopt);
  uint64_t high = {high};
  std::cout << "cells " << high << "\\n" << "low " << {low} << "\\n";
  for (uint64_t i = 0; i < high && i < sortedIdx.size(); i++) std::cout << "cell " << sortedIdx[i] << "\\n";
  for (const auto& b : trueBarcodes) std::cout << "white " << b << "\\n";
  return 0;
}}
"""
    with open(out, "w") as handle:
        handle.write(program)


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
